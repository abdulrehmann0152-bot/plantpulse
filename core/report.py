"""PDF report for one piece of equipment. Charts are drawn directly with fpdf2 (no extra libraries)."""
import math
from datetime import datetime

import pandas as pd
from fpdf import FPDF, FontFace

NAVY, TEAL, RED, AMB, GRN, GREY, LIGHT = (11, 37, 69), (19, 168, 158), (214, 69, 80), (245, 166, 35), (46, 158, 91), (120, 130, 140), (244, 247, 250)
STATUS = {"ok": ("HEALTHY", GRN), "warning": ("WATCH", AMB), "critical": ("ACTION NEEDED", RED), "nodata": ("NO DATA", GREY)}
NAMES = {"heat_exchanger": "Heat exchanger", "pump": "Pump and pipeline"}


def _t(s):
    """Core PDF fonts are Latin-1 only: replace anything else."""
    s = str(s).replace("\u2212", "-").replace("\u2013", "-").replace("\u2265", ">=").replace("\u2264", "<=").replace("\u03b7", "eta")
    return s.encode("latin-1", "replace").decode("latin-1")


class _PDF(FPDF):
    title_text = "PlantPulse | Equipment Performance Report"

    def header(self):
        self.set_fill_color(*NAVY)
        self.rect(0, 0, 210, 14, "F")
        self.set_xy(15, 4)
        self.set_font("Helvetica", "B", 12)
        self.set_text_color(255, 255, 255)
        self.cell(120, 6, self.title_text)
        self.set_font("Helvetica", "", 8)
        self.cell(60, 6, "Learn it in class. Monitor it in the plant.", align="R")
        self.set_text_color(*NAVY)
        self.set_y(20)

    def footer(self):
        self.set_y(-12)
        self.set_font("Helvetica", "", 7)
        self.set_text_color(*GREY)
        self.cell(0, 5, f"Screening report generated by PlantPulse on {datetime.now():%d %b %Y %H:%M}. Page {self.page_no()}", align="C")


def _chart(pdf, x0, y0, w, h, title, series, hlines=()):
    """series: [(name, xs, ys, rgb, dashed)]; xs are datetimes; hlines: [(y, rgb, label)]."""
    pdf.set_xy(x0, y0)
    pdf.set_font("Helvetica", "B", 9)
    pdf.set_text_color(*NAVY)
    pdf.cell(w, 5, _t(title))
    lx = x0 + 14
    pdf.set_font("Helvetica", "", 7)
    for name, _, _, rgb, dashed in series:
        pdf.set_draw_color(*rgb)
        pdf.set_line_width(0.6)
        pdf.line(lx, y0 + 7.5, lx + 6, y0 + 7.5)
        pdf.set_xy(lx + 7, y0 + 5.5)
        pdf.set_text_color(*NAVY)
        pdf.cell(pdf.get_string_width(_t(name)) + 3, 4, _t(name))
        lx += 12 + pdf.get_string_width(_t(name))
    px, py, pw, ph = x0 + 14, y0 + 11, w - 17, h - 21
    xs_all = [x.timestamp() for _, xs, _, _, _ in series for x in xs]
    ys_all = [y for _, _, ys, _, _ in series for y in ys if pd.notna(y)] + [y for y, _, _ in hlines]
    if not xs_all or not ys_all:
        return
    xmin, xmax = min(xs_all), max(xs_all)
    ymin, ymax = min(ys_all), max(ys_all)
    pad = (ymax - ymin) * 0.08 or 1.0
    ymin, ymax = ymin - pad, ymax + pad
    xspan = (xmax - xmin) or 1.0

    def sx(x):
        return px + (x - xmin) / xspan * pw

    def sy(y):
        return py + ph - (y - ymin) / (ymax - ymin) * ph

    pdf.set_line_width(0.15)
    pdf.set_font("Helvetica", "", 6.5)
    raw = (ymax - ymin) / 4
    mag = 10 ** math.floor(math.log10(raw))
    step = next(m * mag for m in (1, 2, 2.5, 5, 10) if raw <= m * mag)
    yv = math.ceil(ymin / step) * step
    while yv <= ymax + 1e-9:
        pdf.set_draw_color(225, 229, 234)
        pdf.line(px, sy(yv), px + pw, sy(yv))
        pdf.set_xy(x0, sy(yv) - 1.8)
        pdf.set_text_color(*GREY)
        pdf.cell(13, 3.6, f"{yv:.0f}" if step >= 1 else (f"{yv:.1f}" if step >= 0.1 else f"{yv:.2f}"), align="R")
        yv += step
    for i in range(4):
        xv = xmin + xspan * i / 3
        pdf.set_xy(sx(xv) - 8, py + ph + 1)
        pdf.cell(16, 3.6, datetime.fromtimestamp(xv).strftime("%d %b"), align="C")
    pdf.set_draw_color(180, 188, 196)
    pdf.rect(px, py, pw, ph)
    for y, rgb, label in hlines:
        pdf.set_draw_color(*rgb)
        pdf.set_line_width(0.3)
        pdf.set_dash_pattern(dash=2, gap=1.5)
        pdf.line(px, sy(y), px + pw, sy(y))
        pdf.set_dash_pattern()
        pdf.set_xy(px + pw - 40, sy(y) - 3.6)
        pdf.set_text_color(*rgb)
        pdf.cell(40, 3.4, _t(label), align="R")
    for _, xs, ys, rgb, dashed in series:
        pts = [(sx(x.timestamp()), sy(y)) for x, y in zip(xs, ys) if pd.notna(y)]
        pdf.set_draw_color(*rgb)
        pdf.set_line_width(0.5)
        if len(pts) > 1:
            if dashed:
                pdf.set_dash_pattern(dash=1.2, gap=0.8)
            pdf.polyline(pts)
            pdf.set_dash_pattern()


def _boxes(pdf, items, per_row):
    w, h = 180 / per_row, 15
    y = pdf.get_y()
    for i, (label, value) in enumerate(items):
        x = 15 + (i % per_row) * w
        yy = y + (i // per_row) * (h + 2)
        pdf.set_fill_color(*LIGHT)
        pdf.set_draw_color(225, 229, 234)
        pdf.rect(x, yy, w - 2, h, "DF")
        pdf.set_xy(x + 2, yy + 1.5)
        pdf.set_font("Helvetica", "", 7)
        pdf.set_text_color(*GREY)
        pdf.cell(w - 6, 4, _t(label))
        pdf.set_xy(x + 2, yy + 6)
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(*NAVY)
        pdf.cell(w - 6, 6, _t(value))
    pdf.set_y(y + ((len(items) - 1) // per_row + 1) * (h + 2) + 2)


def _heading(pdf, text):
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(*NAVY)
    pdf.set_x(15)
    pdf.cell(0, 7, _t(text), new_x="LMARGIN", new_y="NEXT")


def _para(pdf, text, size=9, color=NAVY, bold=False):
    pdf.set_x(15)
    pdf.set_font("Helvetica", "B" if bold else "", size)
    pdf.set_text_color(*color)
    pdf.multi_cell(180, 4.6, _t(text), new_x="LMARGIN", new_y="NEXT")


ACTIONS = {
    "heat_exchanger": ["Plan cleaning or inspection of the exchanger.",
                       "Check whether Rf is rising steadily (fouling) or jumped suddenly (flow or instrument change).",
                       "Confirm flow meters and temperature sensors; the heat balance mismatch shows data quality."],
    "pump_degraded": ["Check impeller and wear rings for wear or damage.", "Check pump speed and suction conditions (strainer, NPSH).",
                      "Compare with the datasheet curve after maintenance."],
    "system_resistance": ["Check that valves are open as intended.", "Check strainers, filters and scaling in the line.",
                          "Test valve positions with the What-if tab on the Pump page."],
}


def build_report(kind, eq, res, alerts, status, text, user, note="", has_demo=False, thresholds=(10.0, 25.0), events=None, compress=True):
    """Return the PDF as bytes. res: analysed DataFrame (rows with errors allowed)."""
    good = res[res["error"] == ""]
    p = eq["params"]
    warn, crit = thresholds
    pdf = _PDF(format="A4")
    pdf.set_compression(compress)
    pdf.set_margins(15, 20, 15)
    pdf.set_auto_page_break(True, margin=16)
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(*NAVY)
    pdf.cell(0, 8, _t(f"{eq['tag']} - {NAMES[kind]}"), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(*GREY)
    role = "Student" if user.get("role") == "student" else "Plant engineer"
    pdf.cell(0, 5, _t(f"Location: {eq['location'] or 'not specified'}   |   Prepared by: {user.get('name', '-')} ({role})"),
             new_x="LMARGIN", new_y="NEXT")
    if not res.empty:
        pdf.cell(0, 5, f"Readings: {len(res)} from {res['timestamp'].min():%d %b %Y} to {res['timestamp'].max():%d %b %Y}",
                 new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)

    label, color = STATUS[status]
    y = pdf.get_y()
    pdf.set_fill_color(*color)
    pdf.rect(15, y, 2.5, 16, "F")
    pdf.set_fill_color(*LIGHT)
    pdf.rect(17.5, y, 177.5, 16, "F")
    pdf.set_xy(20, y + 1.2)
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(*color)
    pdf.cell(0, 5, label)
    pdf.set_xy(20, y + 6.2)
    pdf.set_font("Helvetica", "", 8.5)
    pdf.set_text_color(*NAVY)
    pdf.multi_cell(170, 4.2, _t(text), new_x="LMARGIN", new_y="NEXT")
    pdf.set_y(y + 19)
    if has_demo:
        _para(pdf, "Note: this report includes synthetic demo readings generated from the physical model. They are not plant measurements.",
              8, RED, True)
    if note:
        _para(pdf, f"{'User note' if has_demo else 'Data source note'}: {note}", 8, GREY)
    pdf.ln(1)

    if good.empty:
        _para(pdf, "No valid readings could be analysed.")
        return bytes(pdf.output())
    last = good.iloc[-1]
    ts, tg = list(good["timestamp"]), good

    if kind == "heat_exchanger":
        _boxes(pdf, [("Latest overall U", f"{last['u']:,.0f} W/m2K"), ("U loss vs clean", f"{last['u_loss_pct']:.1f} %"),
                     ("Fouling resistance Rf", f"{last['rf']:.6f} m2K/W"), ("Duty (observed)", f"{last['q_kw']:,.0f} kW"),
                     ("Duty lost vs clean twin", f"{last['q_expected_kw'] - last['q_kw']:,.0f} kW"), ("Shortfall vs twin", f"{last['shortfall_pct']:.1f} %")], 3)
        uc = p["u_clean"]
        y0 = pdf.get_y()
        _chart(pdf, 15, y0, 180, 62, "Overall U over time",
               [("Observed U (W/m2K)", ts, list(tg["u"]), TEAL, False)],
               [(uc, GRN, "Clean U"), (uc * (1 - warn / 100), AMB, f"{warn:g}% loss (watch)"), (uc * (1 - crit / 100), RED, f"{crit:g}% loss (act)")])
        y0 += 64
        _chart(pdf, 15, y0, 180, 62, "Digital twin: cold outlet temperature",
               [("Observed (deg C)", ts, list(tg["tc_out_observed"]), RED, False), ("Twin, clean exchanger (deg C)", ts, list(tg["tc_out_expected"]), GRN, True)])
        pdf.set_y(y0 + 64)
        actions = ACTIONS["heat_exchanger"]
    else:
        _boxes(pdf, [("Latest flow", f"{last['flow_m3_h']:,.0f} m3/h"), ("Latest head", f"{last['head_m']:.1f} m"),
                     ("Deviation from pump curve", f"{last['pump_dev_pct']:+.1f} %"), ("Deviation from system curve", f"{last['sys_dev_pct']:+.1f} %")], 4)
        y0 = pdf.get_y()
        _chart(pdf, 15, y0, 180, 62, "Head: measured vs expected",
               [("Measured (m)", ts, list(tg["head_m"]), RED, False), ("Expected on pump curve (m)", ts, list(tg["h_pump_expected"]), TEAL, True),
                ("Expected on system curve (m)", ts, list(tg["h_sys_expected"]), NAVY, True)])
        y0 += 64
        _chart(pdf, 15, y0, 180, 62, "Deviation from the twin (%)",
               [("Vs pump curve", ts, list(tg["pump_dev_pct"]), TEAL, False), ("Vs system curve", ts, list(tg["sys_dev_pct"]), NAVY, False)],
               [(5, AMB, "+5%"), (-5, AMB, "-5%")])
        pdf.set_y(y0 + 64)
        actions = ACTIONS.get(last["status"], [])

    _heading(pdf, "Alerts")
    if alerts:
        pdf.set_font("Helvetica", "", 8.5)
        pdf.set_text_color(*NAVY)
        pdf.set_draw_color(200, 205, 210)
        with pdf.table(col_widths=(26, 22, 62, 70), text_align="LEFT", line_height=4.4,
                       headings_style=FontFace(emphasis="BOLD", color=(255, 255, 255), fill_color=NAVY)) as table:
            row = table.row()
            for h in ("First seen", "Severity", "Rule", "Details"):
                row.cell(h)
            for a in alerts:
                row = table.row()
                for v in (a["first_seen"], a["severity"], a["rule"], a["detail"]):
                    row.cell(_t(v))
    else:
        _para(pdf, "No alerts. All readings are within limits.")
    pdf.ln(3)
    if actions and status in ("warning", "critical"):
        _heading(pdf, "Suggested actions / possible causes to check")
        for a in actions:
            _para(pdf, f"- {a}")
        pdf.ln(2)

    if events:
        if pdf.get_y() > 230:
            pdf.add_page()
        _heading(pdf, "Notes on the data")
        for ev in events[:12]:
            _para(pdf, f"- {ev['note_date']}: {ev['note'][:300]}", 8.5)
        pdf.ln(2)
    if pdf.get_y() > 225:
        pdf.add_page()
    _heading(pdf, "Method and assumptions")
    if kind == "heat_exchanger":
        arr = {"counter": "counter-flow", "parallel": "parallel flow", "shell_1_2": "1 shell pass / 2 tube passes"}[p["flow"]]
        _para(pdf, f"Equipment: area {p['area_m2']:g} m2, clean U {p['u_clean']:g} W/m2K, {arr}.", 8.5)
        _para(pdf, "Heat duty Q = m Cp dT (average of hot and cold side); U = Q / (A F LMTD); fouling resistance Rf = 1/U - 1/U_clean. "
                   "The digital twin predicts the clean exchanger's outlet temperatures with the effectiveness-NTU method at the same flows and inlet "
                   "temperatures. Alerts: U more than " + f"{warn:g}% (watch) or {crit:g}% (act) below clean; hot/cold duty mismatch above 5% flags instrument problems.", 8.5)
    else:
        _para(pdf, f"Equipment: pipe {p['d_mm']:g} mm x {p['length_m']:g} m, {p['material']}, fittings K = {p['sum_k']:g}, static head {p['static_m']:g} m.", 8.5)
        _para(pdf, "System curve H = H_static + (f L/D + K) v^2/2g with Swamee-Jain friction factor; pump curve is a quadratic fitted to three datasheet points. "
                   "Each reading is compared with both curves (+/-5% tolerance); an alert needs two consecutive readings. Pump wear appears as a negative deviation "
                   "from the pump curve; extra line resistance appears as a positive deviation from the system curve.", 8.5)
    _para(pdf, "This is a screening aid based on the readings supplied. Confirm findings by inspection before maintenance decisions.", 8, GREY)
    return bytes(pdf.output())
